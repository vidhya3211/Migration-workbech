-- Capita Policy Admin - Level Term Assurance schema (Oracle)
CREATE TABLE CAPITA.POLICY (
    POL_NUMBER      VARCHAR2(10)   NOT NULL,
    POL_STATUS      CHAR(1)        NOT NULL,
    SMOKER_FLAG     CHAR(1)        DEFAULT 'N' NOT NULL,
    PAY_FREQ        CHAR(1)        NOT NULL,
    HOLDER_AGE      NUMBER(2)      NOT NULL,
    TERM_YEARS      NUMBER(2)      NOT NULL,
    SUM_ASSURED     NUMBER(11,2)   NOT NULL,
    BASE_RATE       NUMBER(5,4)    NOT NULL,
    FUND_VALUE      NUMBER(11,2),
    YEARS_IN_FORCE  NUMBER(2)      NOT NULL,
    MONTHLY_PREMIUM NUMBER(9,2)    NOT NULL,
    CUST_ID         VARCHAR2(10)   NOT NULL,
    START_DT        CHAR(8)        NOT NULL,
    LAST_PREM_DT    CHAR(8),
    CONSTRAINT PK_POLICY PRIMARY KEY (POL_NUMBER),
    CONSTRAINT CK_POL_STATUS CHECK (POL_STATUS IN ('A','L','P','R')),
    CONSTRAINT CK_PAY_FREQ CHECK (PAY_FREQ IN ('A','M')),
    CONSTRAINT CK_HOLDER_AGE CHECK (HOLDER_AGE BETWEEN 18 AND 75)
);

CREATE TABLE CAPITA.CUSTOMER (
    CUST_ID         VARCHAR2(10)   NOT NULL,
    CUST_NAME       VARCHAR2(80)   NOT NULL,
    DOB             DATE           NOT NULL,
    POSTCODE        VARCHAR2(8),
    NI_NUMBER       VARCHAR2(9),
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUST_ID)
);

COMMENT ON COLUMN CAPITA.POLICY.START_DT IS 'Policy start date, YYYYMMDD';
COMMENT ON COLUMN CAPITA.POLICY.MONTHLY_PREMIUM IS 'Monthly premium including administration charge';

CREATE OR REPLACE TRIGGER CAPITA.TRG_POLICY_AUDIT
    BEFORE UPDATE ON CAPITA.POLICY
    FOR EACH ROW;
