"""Code-generation agent (T2): transformation code + unit tests from *certified* mappings only (UC7).

Code is generated deterministically from the certified transformation specs (templates, not free-form LLM
code). Generated code is untrusted until it passes the unsafe-code guardrail, compiles, and its tests pass
in the sandbox. Tests use synthetic values derived from the specs - never customer data.
"""
from __future__ import annotations

import json
import re
from collections import defaultdict

from blackboard.identity import agent_identity, register_agent
from schemas.signals import SignalType as S
from agents.base import AgentOutput, BaseAgent
from guardrails.pipeline import GuardrailContext, GuardrailViolation, Stage
from guardrails.security.code_policy import CodeSubject
from reasoning.deterministic.transform import TRANSFORM_VERSION, TransformError, apply
from schemas.common import Tier, ReasoningMode, stable_id
from schemas.mapping import GeneratedCode, MappingProposal
from schemas.signals import SignalLevel, SignalType

SAMPLE = {"string": "AB12345678", "integer": "42", "decimal": "1234.56", "date": "2021-03-15", "boolean": "Y"}


def _ident(s: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", s.lower()).strip("_") or "x"


def _sample_value(m: MappingProposal) -> str:
    t = m.transformation
    if t.kind == "code_map":
        return min(t.params.get("map", {}))
    if t.kind == "date_format":
        return "20210315" if t.params.get("from") == "%Y%m%d" else "2021-03-15"
    return SAMPLE.get(m.source.data_type or "string", "X")


def render_module(mappings: list[MappingProposal]) -> str:
    lines = [f'"""Generated by AI Workbench codegen_agent ({TRANSFORM_VERSION}) from certified mappings.',
             "", "Mapping ids: " + ", ".join(m.mapping_id for m in mappings), "Do not edit by hand - regenerate.",
             '"""', "from datetime import datetime", "from decimal import Decimal", "", ""]
    maps: dict[str, str] = {}
    for m in mappings:
        if m.transformation.kind == "code_map":
            name = f"CODE_MAP_{_ident(m.source.field).upper()}"
            maps[m.mapping_id] = name
            lines.append(f"{name} = {json.dumps(m.transformation.params.get('map', {}), sort_keys=True)}")
    lines += ["", "", "def _date(value, sentinels, fmt):",
              "    if value is None or value.strip() in sentinels:", "        return None",
              "    if fmt == 'iso':", "        return datetime.strptime(value.strip(), '%Y-%m-%d').date().isoformat()",
              "    return datetime.strptime(value.strip(), fmt).date().isoformat()", "", "",
              "def _code(table, value, field):", "    if value not in table:",
              "        raise ValueError(f'{field}: code {value!r} has no certified mapping')", "    return table[value]", "", "",
              "def _decimal(value, scale):", "    if value is None or value.strip() == '':", "        return None",
              "    d = Decimal(value.strip())",
              "    return format(d.quantize(Decimal(1).scaleb(-scale)) if scale is not None else d, 'f')",
              "", "", "def transform(row):", f'    """{mappings[0].source.entity} -> {mappings[0].target.entity}."""',
              "    out = {}"]
    for m in mappings:
        src, tgt, t = json.dumps(m.source.field), json.dumps(m.target.field), m.transformation
        if t.kind == "code_map":
            expr = f"_code({maps[m.mapping_id]}, row.get({src}), {src})"
        elif t.kind == "date_format":
            expr = f"_date(row.get({src}), {json.dumps(t.params.get('null_sentinels', []))}, {json.dumps(t.params.get('from', 'iso'))})"
        elif t.kind == "cast" and t.params.get("to") == "decimal":
            expr = f"_decimal(row.get({src}), {t.params.get('scale')!r})"
        elif t.kind == "cast" and t.params.get("to") == "integer":
            expr = f"str(int(Decimal(row.get({src}))))"
        else:
            expr = f"row.get({src})"
        lines.append(f"    out[{tgt}] = {expr}  # {m.mapping_id}: {t.description}")
    lines += ["    return out", ""]
    return "\n".join(lines)


def render_tests(module: str, mappings: list[MappingProposal]) -> str:
    row = {m.source.field: _sample_value(m) for m in mappings}
    expected = {}
    for m in mappings:
        try:
            expected[m.target.field] = apply(m.transformation, row[m.source.field])
        except TransformError:
            expected[m.target.field] = None
    lines = [f'"""Generated tests for {module} - synthetic values only, derived from the certified specs."""',
             "import pytest", "", f"from {module} import transform", "", "",
             "def test_transform_example_row():", f"    row = {json.dumps(row, sort_keys=True)}",
             f"    assert transform(row) == {json.dumps(expected, sort_keys=True)}", ""]
    for m in mappings:
        t = m.transformation
        if t.kind == "code_map" and t.params.get("strict", True):
            lines += ["", f"def test_unmapped_code_rejected_{_ident(m.source.field)}():",
                      f"    row = {json.dumps(row, sort_keys=True)}", f"    row[{json.dumps(m.source.field)}] = '??'",
                      "    with pytest.raises(ValueError):", "        transform(row)", ""]
        if t.kind == "date_format" and t.params.get("null_sentinels"):
            lines += ["", f"def test_sentinel_date_becomes_null_{_ident(m.source.field)}():",
                      f"    row = {json.dumps(row, sort_keys=True)}",
                      f"    row[{json.dumps(m.source.field)}] = {json.dumps(t.params['null_sentinels'][0])}",
                      f"    assert transform(row)[{json.dumps(m.target.field)}] is None", ""]
    return "\n".join(lines)


@register_agent
class CodegenAgent(BaseAgent):
    IDENTITY = agent_identity("codegen_agent", Tier.T2, "mapping_build", 'Generates transformation code + unit tests from certified mappings', {S.GENERATED_CODE}, tools={'sandbox.run_tests'}, proposes={'generated_code'})

    def run(self, certified_mappings: list[MappingProposal], **_: object) -> AgentOutput:
        groups: dict[tuple[str, str], list[MappingProposal]] = defaultdict(list)
        for m in certified_mappings:
            groups[(m.source.entity, m.target.entity)].append(m)
        out: list[GeneratedCode] = []
        for (se, te), ms in sorted(groups.items()):
            module = f"generated_{_ident(se)}_to_{_ident(te)}"
            source, tests = render_module(ms), render_tests(module, ms)
            validation: dict = {"transform_version": TRANSFORM_VERSION}
            ctx = GuardrailContext(self.run_id, self.name)
            try:
                for label, code in (("module", source), ("tests", tests)):
                    self.services.guardrails.run(Stage.OUTPUT_SCHEMA, CodeSubject(code, f"{module}:{label}"), ctx,
                                                 only={"unsafe_generated_code"})
                compile(source, module, "exec")
                validation["static_checks"] = "passed"
                result = self.tool("sandbox.run_tests", {"module_name": module, "source": source, "tests": tests})
                validation.update({"tests_passed": result.passed, "sandbox_output": result.output[-800:]})
            except GuardrailViolation as exc:
                validation.update({"static_checks": "blocked", "reason": str(exc)})
            except SyntaxError as exc:
                validation.update({"static_checks": "syntax_error", "reason": str(exc)})
            out.append(GeneratedCode(code_id=stable_id("GEN", self.run_id, module), run_id=self.run_id,
                                     mapping_ids=[m.mapping_id for m in ms], module_name=module, source=source,
                                     tests=tests, validation=validation))
            level = SignalLevel.INFO if validation.get("tests_passed") else SignalLevel.WARN
            self.signal(SignalType.GENERATED_CODE, f"{module}: {len(ms)} mapping(s); tests "
                        f"{'passed' if validation.get('tests_passed') else 'did not pass'}", level=level,
                        item_refs=[m.mapping_id for m in ms], data={"module": module, **{k: v for k, v in validation.items()
                                                                                          if k != 'sandbox_output'}})
        self.note_mode(ReasoningMode.DETERMINISTIC)
        return AgentOutput(items={"generated_code": out})
